"""The plant's topology, in the form Atlas's grouping already requires.

`phos.atlas.topology` refuses to infer which signals share a physical unit, for a reason that
holds just as firmly here: grouping exists to answer "did these deviations share a cause?", so
membership derived from co-movement would answer that question with the statistics that raised the
deviations. Every `Subsystem` therefore carries a `source` naming the documentation the assignment
came from.

For a simulated plant that source is unusual, and worth being explicit about rather than quietly
strong. A real corpus's topology is a *reading* of a P&ID or a vendor manual, and can be wrong. A
synthetic plant's topology is the declaration the simulation itself was built from — the same
`SignalSpec.physical_unit` the physics reads — so it is exact by construction. That makes it
better ground truth than any real corpus can offer, and it is precisely why a grouping reduction
measured on synthetic data must not be read as a reduction achievable on a real plant, where the
map is a claim rather than a fact. The `source` string says so, on every subsystem, so a reviewer
reading the topology file sees it without reading this module.

Two forms come out, and they are the same declaration: a `SubsystemMap` for a caller working in
memory, and the TOML file `phos.atlas.topology.load_topology` reads, so a generated corpus ships
its topology exactly as HAI does.
"""

import json
import logging
from pathlib import Path
from typing import Final

from phos.atlas.topology import SCHEMA_VERSION, Subsystem, SubsystemMap
from phos.synth.plant import PlantDescription

__all__ = [
    "SYNTHETIC_TOPOLOGY_CAVEAT",
    "subsystem_map",
    "subsystems",
    "topology_toml",
    "write_topology",
]

logger = logging.getLogger(__name__)

SYNTHETIC_TOPOLOGY_CAVEAT: Final = (
    "This topology is EXACT rather than merely documented: it is the same declaration the "
    "simulation's physics reads, so no instrument is on a unit other than the one named here. A "
    "real corpus's topology is a reading of process documentation and can be wrong. Any grouping "
    "result measured against this map is therefore an upper bound on what the same grouping would "
    "achieve on a real plant."
)
"""Written into every generated topology file, beside each subsystem's source."""


def subsystems(description: PlantDescription) -> tuple[Subsystem, ...]:
    """Return one `Subsystem` per physical unit, carrying the signals instrumented on it.

    Args:
        description: The plant.

    Returns:
        The subsystems in the plant's declared unit order. Every signal appears exactly once,
        which `SubsystemMap` requires and `PlantDescription` already guarantees by refusing a
        signal on an undeclared unit and a unit with no signals.
    """
    source = (
        f"Declared by the simulation that generated this corpus: "
        f"phos.synth.plants -> {description.plant_id} -> SignalSpec.physical_unit. "
        f"{SYNTHETIC_TOPOLOGY_CAVEAT}"
    )
    return tuple(
        Subsystem(
            subsystem_id=unit.unit_id,
            label=unit.label,
            signals=frozenset(
                signal.key for signal in description.signals if signal.physical_unit == unit.unit_id
            ),
            source=source,
        )
        for unit in description.units
    )


def subsystem_map(description: PlantDescription) -> SubsystemMap:
    """Return the plant's topology as the partition Atlas's grouping consumes.

    Args:
        description: The plant.

    Returns:
        A validated `SubsystemMap` over exactly the plant's signal set.

    Raises:
        TopologyError: If the declaration does not partition the signals. Unreachable for a
            `PlantDescription`, which enforces the same invariants at construction — but checked
            here rather than assumed, because the two could drift apart.
    """
    return SubsystemMap(subsystems(description), description.signal_keys())


def topology_toml(description: PlantDescription) -> str:
    """Render the topology in the file format `phos.atlas.topology.load_topology` reads.

    Args:
        description: The plant.

    Returns:
        The complete file contents, deterministic for a given plant: units in declaration order,
        signals sorted within each unit.
    """
    lines = [
        f"#  {description.label} — subsystem topology",
        "#",
        "#  Generated by phos.synth. Do not hand-edit: the authority is",
        f"#  SignalSpec.physical_unit in the {description.plant_id} plant model, and this",
        "#  file is a rendering of it.",
        "#",
        f"#  {description.industry}",
        "#",
        f"schema_version = {SCHEMA_VERSION}",
        f"corpus = {json.dumps(description.plant_id)}",
    ]
    for subsystem in subsystems(description):
        lines.extend(
            [
                "",
                "[[subsystems]]",
                f"subsystem_id = {json.dumps(subsystem.subsystem_id)}",
                f"label = {json.dumps(subsystem.label)}",
                f"source = {json.dumps(subsystem.source)}",
                "signals = [",
                *(f"    {json.dumps(signal)}," for signal in sorted(subsystem.signals)),
                "]",
            ]
        )
    return "\n".join(lines) + "\n"


def write_topology(description: PlantDescription, path: Path) -> None:
    """Write the plant's topology declaration to ``path``, overwriting it if it exists."""
    path.write_text(topology_toml(description), encoding="utf-8")
    logger.debug("wrote topology for %s to %s", description.plant_id, path)
