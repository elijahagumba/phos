"""A sealed batch: seeds that never enter a repository, and a fingerprint that does.

The problem this module exists for is narrow and worth stating exactly. A seed number typed into
a file, a script, a commit message, or a shell history is a seed somebody can read. A private exam
built from such a seed is private in name only, because the person who reads the seed can
regenerate the plant, look at it, and tune against it. The referee already refuses to let a seed
live in two pools (`phos.referee.seeds`), and the generator already keeps sealed families behind
an environment switch (`phos.synth.families`), but neither of those says anything about *where a
seed came from*. A pool file can be a list of numbers someone chose after seeing a score.

So this module does three things and no more.

**It takes seeds from the environment and never writes them.** A sealed batch is described by a
`SealedBatch` holding (family, seed) pairs, and it can only be built by `batch_from_environment`,
which reads `PHOS_SEALED_SEEDS`. Nothing here has a field, a log line, a `repr`, or an error
message that carries a seed value. A test asserts that, because "we remembered not to print it" is
not a guarantee.

**It commits a fingerprint instead.** `fingerprint` is a SHA-256 digest over a canonical encoding
of the sorted pairs, prefixed with the encoding's own version so a change to the encoding makes a
different digest rather than a silently different meaning. The digest is safe to commit: it names
a set without disclosing it, and it lets a later run check that the seeds it was given are the
seeds this batch was registered as.

**It refuses the ways a batch could be relabelled.** A batch cannot contain a seed that already
lives in a development, public or retired pool, because that seed has been looked at or published.
It cannot draw from an open family, because then a plant from it could be regenerated by anyone
with the open family and a seed guess. And a batch whose recomputed digest does not match the
registered one is refused rather than accepted with a warning, which is the difference between a
seal and a note.

**Honest limit, stated rather than hidden.** A digest over seeds is only as strong as the seed
space. If a family draws from a small integer range, anyone holding the digest can enumerate
candidate sets and find the one that matches. This module does not measure the seed space, and no
bar in E-0016 claims it does. The seal rests on seeds being large enough that enumeration is
infeasible, which is a property of how the seeds are chosen, not of this code.
"""

from __future__ import annotations

import hashlib
import json
import os
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from phos.referee.seeds import SeedEntry, SeedPool, SeedVault, SeedVaultError
from phos.synth.families import SEALED_ENV_VAR, FamilyError, PlantFamily, get_family

__all__ = [
    "ENV_VAR",
    "FINGERPRINT_VERSION",
    "SealedBatch",
    "SealedBatchError",
    "batch_from_environment",
    "fingerprint",
]

#: Where the seeds are read from. A JSON list of ``{"family": ..., "seed": ...}`` objects.
#: Point it at a file on an encrypted volume; nothing here knows or cares where it lives.
ENV_VAR: Final = "PHOS_SEALED_SEEDS"

#: Prefixes the canonical encoding. Bumping it changes every digest, which is the point: an
#: encoding change must not leave two different meanings sharing one digest.
FINGERPRINT_VERSION: Final = "phos-sealed-batch-1"


class SealedBatchError(ValueError):
    """Raised when a sealed batch cannot be built, or a check on one fails."""


@dataclass(frozen=True)
class SealedBatch:
    """A set of (family, seed) pairs that is meant to stay secret.

    Construct it with `batch_from_environment` rather than directly: the constructor takes the
    seeds, and the whole discipline here is that only one function in the codebase ever holds
    them, and it reads them from an environment variable.

    Attributes:
        entries: The pairs, sorted by (family, seed). Sorted because the fingerprint must not
            depend on the order the pairs happened to be listed in.
    """

    entries: tuple[SeedEntry, ...]

    def __post_init__(self) -> None:
        """Refuse an empty batch or a duplicate pair.

        Raises:
            SealedBatchError: If there are no entries, or a pair appears twice.
        """
        if not self.entries:
            raise SealedBatchError("a sealed batch with no entries is not a batch")
        keys = [entry.key() for entry in self.entries]
        if len(set(keys)) != len(keys):
            raise SealedBatchError("a sealed batch names the same (family, seed) pair twice")

    def __repr__(self) -> str:
        """Return a representation that names the count and the digest, never a seed.

        Returns:
            A string safe to print, log or paste into a commit message.
        """
        return f"SealedBatch({len(self.entries)} plants, fingerprint={self.digest()[:16]}...)"

    __str__ = __repr__

    def digest(self) -> str:
        """Return the fingerprint this batch is registered by."""
        return fingerprint(self.entries)

    def families(self) -> tuple[str, ...]:
        """Return the family ids this batch draws from, sorted and deduplicated."""
        return tuple(sorted({entry.family for entry in self.entries}))


def fingerprint(entries: Sequence[SeedEntry]) -> str:
    """Return the SHA-256 fingerprint of a set of (family, seed) pairs.

    The encoding is fixed and documented rather than left to a chance of `repr`: the version tag,
    then for each pair in sorted order, the family id, a unit separator, the seed as a decimal,
    and a record separator. A different order gives the same digest because sorting happens here.

    Args:
        entries: The pairs. An empty sequence is allowed and gives a digest of the empty set,
            which is a useful value for "no batch registered yet".

    Returns:
        The digest, as 64 lowercase hex characters.
    """
    ordered = sorted(entries, key=lambda entry: entry.key())
    digest = hashlib.sha256()
    digest.update(FINGERPRINT_VERSION.encode("utf-8"))
    for entry in ordered:
        digest.update(b"\x1e")
        digest.update(entry.family.encode("utf-8"))
        digest.update(b"\x1f")
        digest.update(str(entry.seed).encode("utf-8"))
    return digest.hexdigest()


def _parse_seed_pairs(raw: object, origin: str) -> tuple[SeedEntry, ...]:
    """Turn the parsed JSON into entries, refusing anything that is not a family and an integer.

    Args:
        raw: The parsed JSON value.
        origin: Where it came from, for the error message. Never includes a seed.

    Returns:
        The pairs.

    Raises:
        SealedBatchError: If the value is not a list of objects with a family string and an
            integer seed.
    """
    if not isinstance(raw, list):
        raise SealedBatchError(f"{origin}: expected a JSON list of seed entries")
    entries: list[SeedEntry] = []
    for position, item in enumerate(raw):
        if not isinstance(item, Mapping):
            raise SealedBatchError(f"{origin}: entry {position} is not an object")
        family = item.get("family")
        seed = item.get("seed")
        if not isinstance(family, str) or not family:
            raise SealedBatchError(f"{origin}: entry {position} has no family string")
        if isinstance(seed, bool) or not isinstance(seed, int):
            raise SealedBatchError(f"{origin}: entry {position} has no integer seed")
        entries.append(SeedEntry(family=family, seed=seed))
    return tuple(entries)


def batch_from_environment(
    *,
    environ: Mapping[str, str] | None = None,
) -> SealedBatch:
    """Build a batch from the file named by `ENV_VAR`, checking every refusal on the way.

    Args:
        environ: The environment to read. Defaults to `os.environ`, and is injectable so a test
            does not have to mutate the real one.

    Returns:
        The batch.

    Raises:
        SealedBatchError: If the variable is unset, the file is missing or malformed, a seed draws
            from an open family, or a pair duplicates one in front of it.
    """
    source = os.environ if environ is None else environ
    path = source.get(ENV_VAR)
    if not path:
        raise SealedBatchError(
            f"{ENV_VAR} is not set. A sealed batch needs its seeds named by a path outside the "
            "repository; this module will not look for them anywhere else"
        )
    location = Path(path)
    if not location.is_file():
        raise SealedBatchError(f"{ENV_VAR} names {location}, which is not a file")

    try:
        raw = json.loads(location.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        # The message deliberately carries the path and the parse failure, never the content.
        raise SealedBatchError(
            f"{location}: could not be read as JSON ({type(error).__name__})"
        ) from error

    entries = _parse_seed_pairs(raw, str(location))
    batch = SealedBatch(entries=tuple(sorted(entries, key=lambda entry: entry.key())))
    for entry in batch.entries:
        _refuse_open_family(entry)
    return batch


def _refuse_open_family(entry: SeedEntry) -> None:
    """Raise if this entry's family is one a plant could be regenerated from publicly.

    A sealed batch has to draw from a sealed family. If it drew from an open one, anyone holding
    the open family and a guessed seed could regenerate a plant in the exam, which makes the seal
    a label. The sealed switch is turned on for the duration of the check so the family can be
    looked up at all, and restored exactly as it was found afterwards, the same discipline
    `phos.referee.seeds.assert_no_sealed_in_open_pools` already uses.

    Args:
        entry: The pair to check.

    Raises:
        SealedBatchError: If the family is open, or does not exist.
    """
    previous = os.environ.get(SEALED_ENV_VAR)
    os.environ[SEALED_ENV_VAR] = "1"
    try:
        try:
            family: PlantFamily = get_family(entry.family)
        except FamilyError as error:
            raise SealedBatchError(
                f"sealed batch names family {entry.family!r}, which does not exist"
            ) from error
        if not family.sealed:
            raise SealedBatchError(
                f"sealed batch names family {entry.family!r}, which is open. A batch built from "
                "an open family can be regenerated by anyone holding that family and a guessed "
                "seed, so it cannot be sealed"
            )
    finally:
        if previous is None:
            os.environ.pop(SEALED_ENV_VAR, None)
        else:
            os.environ[SEALED_ENV_VAR] = previous


def _vault_keys(vault: SeedVault) -> dict[tuple[str, int], SeedPool]:
    """Return every (family, seed) pair in an open pool, and which pool holds it.

    Args:
        vault: The four-pool vault.

    Returns:
        A mapping from pair to the pool it was found in. The retired pool counts, because a seed
        that has been used in an exam has been seen by whoever ran it.
    """
    found: dict[tuple[str, int], SeedPool] = {}
    for pool in (SeedPool.DEV, SeedPool.PUBLIC, SeedPool.RETIRED):
        for entry in vault.load(pool):
            found[entry.key()] = pool
    return found


def refuse_seeds_already_seen(batch: SealedBatch, vault: SeedVault) -> None:
    """Raise if a sealed seed already lives in a development, public or retired pool.

    This is the check that stops a sealed batch being built from a replay. Without it, a batch
    could be "sealed" by copying the development pool, which would put an exam on plants a
    detector was already tuned against.

    Args:
        batch: The candidate batch. Never printed.
        vault: The vault whose open pools are searched.

    Raises:
        SealedBatchError: Naming the pool a seed was found in. The seed itself is named by family
            only, because the message may be logged.
    """
    seen = _vault_keys(vault)
    for entry in batch.entries:
        owner = seen.get(entry.key())
        if owner is not None:
            raise SealedBatchError(
                f"sealed batch seed for family {entry.family!r} already lives in the "
                f"{owner.value!r} pool. A seed that has been looked at cannot stand in for a "
                "secret"
            )


def register_in_vault(batch: SealedBatch, vault: SeedVault) -> None:
    """Write a batch's entries into the private pool, refusing any collision first.

    Args:
        batch: The batch. Never printed.
        vault: The vault to write to.

    Raises:
        SealedBatchError: If any entry already lives in any pool, including the private one, which
            would mean the batch is being appended to a pool that already holds a different seal.
    """
    try:
        vault.check_disjoint()
    except SeedVaultError as error:
        raise SealedBatchError(str(error)) from error
    for pool in SeedPool:
        for entry in vault.load(pool):
            for candidate in batch.entries:
                if entry.key() == candidate.key():
                    raise SealedBatchError(
                        f"sealed batch seed for family {candidate.family!r} already lives in the "
                        f"{pool.value!r} pool"
                    )
    vault.add(SeedPool.PRIVATE, batch.entries)


def check_against_registered(batch: SealedBatch, registered: str) -> None:
    """Raise if a batch's digest is not the one a registry entry holds.

    Args:
        batch: The batch presented for a run. Never printed.
        registered: The digest from the registry or the decision record.

    Raises:
        SealedBatchError: If they differ. The message carries both digests, which are safe to
            print, and no seed.
    """
    actual = batch.digest()
    if actual != registered:
        raise SealedBatchError(
            f"the seeds presented give fingerprint {actual}, and the registered batch is "
            f"{registered}. A batch that does not match the registered one is not the sealed "
            "batch, and refusing it is the whole point of registering one"
        )


def iter_seeds(batch: SealedBatch) -> Iterable[SeedEntry]:
    """Yield a batch's pairs, for the one caller that genuinely needs them: the generator.

    Kept separate from the attributes so a reader grepping for `.seed` finds this door named
    rather than a field reached into from anywhere.

    Args:
        batch: The batch.

    Yields:
        Each pair, in sorted order.
    """
    yield from batch.entries
