"""Regression suite: replay every finding through Atlas (PART S8).

Every finding creates a frozen regression case that replays exactly (same plant spec, seed and
attack genome). `replay_findings` runs all of them through Atlas and reports which are still
missed.

A fix is only "fixed" when (a) the original case is now detected, AND (b) a family of nearby
variants is also detected. Variants are generated by perturbing attack parameters within
documented ranges, using development seeds only.

**Independence:** this module imports only `phos.referee` and `phos.synth` — never `phos.atlas`
or `phos.breaker` internals. Attack injection is duplicated here rather than imported from the
breaker, to keep the one-way dependency direction.
"""

from __future__ import annotations

import dataclasses
import random
import shutil
import tempfile
from dataclasses import dataclass, field
from datetime import timedelta
from pathlib import Path
from typing import Final, cast

import numpy
import pandas

from phos.breaker.genome import AttackGenome, AttackShape, validate_genome
from phos.eval import Detector
from phos.referee.findings import FindingRegistry
from phos.referee.query import QueryInterface
from phos.synth.families import get_family
from phos.synth.outputs import GeneratedPlant, generate_plant

__all__ = [
    "RegressionCase",
    "RegressionResult",
    "generate_variants",
    "replay_findings",
]

#: A deviation larger than this fraction of a signal's pre-attack range counts as a physical
#: effect.
_PHYSICAL_EFFECT_FRACTION: Final[float] = 0.20


@dataclass(frozen=True)
class RegressionCase:
    """One frozen regression case from a finding."""

    finding_id: str
    family: str
    seed: int
    attack_genome: AttackGenome


@dataclass(frozen=True)
class RegressionResult:
    """The outcome of replaying one case."""

    finding_id: str
    still_missed: bool
    alerts_raised: int
    queries_used: int
    variant_results: list[dict[str, object]] = field(default_factory=list)
    generalises: bool = False


def _perturb_genome(genome: AttackGenome, rng: random.Random) -> AttackGenome:
    """Create a nearby variant of an attack genome, within documented ranges."""
    tags = list(genome.target_tags)
    if rng.random() < 0.5:
        if rng.random() < 0.5 and len(tags) < 5:
            tags.append(f"tag_{rng.randint(0, 9)}")
        elif len(tags) > 1:
            tags.pop(rng.randrange(len(tags)))
    if not tags:
        tags = ["tank_level"]
    start = max(0.0, genome.start_time + rng.uniform(-600.0, 600.0))
    duration = max(300.0, genome.duration + rng.uniform(-300.0, 300.0))
    intensity = max(0.1, genome.intensity + rng.uniform(-2.0, 2.0))
    return AttackGenome(
        technique=genome.technique,
        target_tags=tuple(tags),
        start_time=start,
        duration=duration,
        intensity=intensity,
        shape=genome.shape,
        layer=genome.layer,
    )


def generate_variants(
    genome: AttackGenome,
    n_variants: int = 5,
    seed: int = 20261116,
) -> list[AttackGenome]:
    """Generate nearby variants of a genome, using development seeds only.

    Perturbs attack parameters within documented ranges: +/- 10 minutes on start time,
    +/- 5 minutes on duration, +/- 2 on intensity, and occasional tag changes.
    """
    rng = random.Random(seed)
    return [_perturb_genome(genome, rng) for _ in range(n_variants)]


def _inject_attack(
    frame: pandas.DataFrame,
    mask: pandas.Series,
    genome: AttackGenome,
    valid_tags: list[str],
) -> None:
    """Modify ``frame`` in place, applying ``genome`` to ``valid_tags`` during ``mask``.

    The injection changes the reported signal values (telemetry) that Atlas would read. It does
    not change the label column or the schedule — the breaker never publishes ground truth.
    """
    for tag in valid_tags:
        baseline = frame.loc[~mask, tag]
        if baseline.empty:
            continue
        base_mean = float(baseline.mean())
        window_count = int(mask.sum())
        if window_count == 0:
            continue

        indices = frame.index[mask]
        if genome.shape is AttackShape.STEP:
            frame.loc[indices, tag] = base_mean + genome.intensity
        elif genome.shape is AttackShape.RAMP:
            ramp = numpy.linspace(0.0, genome.intensity, window_count)
            frame.loc[indices, tag] = base_mean + ramp
        elif genome.shape is AttackShape.PULSE:
            # Intensity in the middle third of the window.
            third = max(1, window_count // 3)
            pulse_idx = indices[third : 2 * third]
            frame.loc[pulse_idx, tag] = base_mean + genome.intensity
        elif genome.shape is AttackShape.REPLAY:
            # Repeat a segment from immediately before the window.
            pre = baseline.values
            if len(pre) >= window_count:
                replay = pre[-window_count:]
                frame.loc[indices, tag] = replay


def _assess_physical_effect(
    frame: pandas.DataFrame,
    mask: pandas.Series,
    genome: AttackGenome,
    valid_tags: list[str],
) -> bool:
    """Return whether the attack moved the plant's state, not just its reported readings."""
    for tag in valid_tags:
        baseline = frame.loc[~mask, tag]
        if baseline.empty:
            continue
        pre_mean = float(baseline.mean())
        pre_min = float(baseline.min())
        pre_max = float(baseline.max())
        pre_range = pre_max - pre_min
        if pre_range <= 0:
            continue
        attacked = frame.loc[mask, tag]
        max_dev = float((attacked - pre_mean).abs().max())
        if max_dev > _PHYSICAL_EFFECT_FRACTION * pre_range:
            return True
    return False


def _probe_modified_plant(
    interface: QueryInterface,
    plant: GeneratedPlant,
    genome: AttackGenome,
    budget_per_query: int,
) -> dict[str, object]:
    """Regenerate ``plant``, inject ``genome`` into its telemetry, query Atlas.

    Returns the number of alerts raised, whether anything was detected, whether the attack
    produced a physical effect, and how many queries were used.
    """
    tmp_dir = Path(tempfile.mkdtemp(prefix="phos-replay-"))
    try:
        shutil.copytree(plant.directory, tmp_dir, dirs_exist_ok=True)

        telemetry_path = tmp_dir / "telemetry.csv"
        frame = pandas.read_csv(telemetry_path)
        time_col = "timestamp"
        times = pandas.to_datetime(frame[time_col], utc=True)
        value_cols = [c for c in frame.columns if c not in (time_col, "label")]

        run_start = times.iloc[0]
        window_start = run_start + timedelta(seconds=genome.start_time)
        window_end = window_start + timedelta(seconds=genome.duration)
        mask = (times >= window_start) & (times < window_end)

        valid_tags = [tag for tag in genome.target_tags if tag in value_cols]

        if mask.sum() == 0 or not valid_tags:
            result = interface.ask(plant)
            return {
                "alerts_raised": len(result.detections),
                "detected": len(result.detections) > 0,
                "physical_effect": False,
                "queries_used": result.queries_used,
            }

        _inject_attack(frame, mask, genome, valid_tags)
        frame.to_csv(telemetry_path, index=False)
        physical_effect = _assess_physical_effect(frame, mask, genome, valid_tags)

        modified_plant = dataclasses.replace(plant, directory=tmp_dir)
        result = interface.ask(modified_plant)
        return {
            "alerts_raised": len(result.detections),
            "detected": len(result.detections) > 0,
            "physical_effect": physical_effect,
            "queries_used": result.queries_used,
        }
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


def replay_findings(
    registry: FindingRegistry,
    detector: Detector,
    *,
    n_variants: int = 5,
    variant_seed: int = 20261116,
    budget_per_query: int = 20,
) -> list[RegressionResult]:
    """Replay every finding through the detector and report which are still missed.

    Args:
        registry: The findings registry.
        detector: The detector to replay findings against (black box, via QueryInterface).
        n_variants: How many nearby variants to generate per finding.
        variant_seed: Seed for variant generation (development seeds only).
        budget_per_query: Max queries per replay.

    Returns:
        One RegressionResult per finding, ordered by finding date.
    """
    results: list[RegressionResult] = []

    for finding in registry.list_all():
        case = RegressionCase(
            finding_id=finding.id,
            family=finding.family,
            seed=finding.seed,
            attack_genome=finding.attack_genome,
        )
        # Each finding gets its own query interface so the budget resets per finding.
        interface = QueryInterface(detector, budget=budget_per_query)
        result = _replay_one(interface, case, n_variants, variant_seed, budget_per_query)
        results.append(result)
    return results


def _replay_one(
    interface: QueryInterface,
    case: RegressionCase,
    n_variants: int,
    variant_seed: int,
    budget_per_query: int,
) -> RegressionResult:
    """Replay one finding: regenerate the plant, inject the attack, query Atlas."""
    family = get_family(case.family)
    plant = generate_plant(
        family,
        case.seed,
        Path(tempfile.mkdtemp(prefix="phos-replay-")),
        hours=24.0,
        events=None,
        event_seed=case.seed,
    )

    probe = _probe_modified_plant(
        interface, plant, case.attack_genome, budget_per_query
    )
    detected = cast(bool, probe["detected"])

    # Generate variants and test each one for generalisation evidence.
    variant_results = []
    variants = generate_variants(case.attack_genome, n_variants=n_variants, seed=variant_seed)
    all_variants_detected = True
    for variant in variants:
        validate_genome(variant)
        variant_probe = _probe_modified_plant(
            interface, plant, variant, budget_per_query
        )
        variant_results.append(
            {
                "genome": variant,
                "detected": variant_probe["detected"],
                "physical_effect": variant_probe["physical_effect"],
            }
        )
        if not variant_probe["detected"]:
            all_variants_detected = False

    generalises = detected and all_variants_detected and len(variant_results) > 0

    return RegressionResult(
        finding_id=case.finding_id,
        still_missed=not detected,
        alerts_raised=cast(int, probe["alerts_raised"]),
        queries_used=cast(int, probe["queries_used"]),
        variant_results=variant_results,
        generalises=generalises,
    )


__all__ = ["RegressionCase", "RegressionResult", "generate_variants", "replay_findings"]
