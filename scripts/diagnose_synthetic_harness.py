"""Run Atlas against the synthetic command-and-maintenance harness and report what happens.

**Everything this script prints is DIAGNOSTIC OUTPUT, not a measured result.** It says what
machinery ran and what it produced on data we wrote, against a plant we simulated. It is not a
detection rate, not a recall figure, not a false-positive rate, and not a number that may be
compared against any frozen public row. Nothing here is appended to `eval_runs/log.jsonl`.

The three questions it exists to answer, all of them about machinery rather than performance:

1. **Does the command path see attacker command actions now that they exist?** Command-lead on the
   public corpora stands at a frozen 0 of 16 for known stations and 1 of 4 for unknown masters, and
   nothing here moves either — they are facts about public data (ADR 0034, 0038-0040). The question
   is narrower and is the only one that can be asked honestly: when an adversary really writes to a
   real register and the write really moves the process, does Atlas's graph comparison produce
   anything at all, and are the two issuer kinds distinguishable?

2. **Does the CMMS join do anything when a real calendar exists?** The inlet has never seen a
   maintenance record (ADR 0069). Here it sees one, generated by a process that could not see the
   attacks.

3. **What happens in the covered-window case?** An attacker acting inside a sanctioned maintenance
   window is the case ADR 0014 and ADR 0069 both name and neither could exercise.

Run:

    uv run python scripts/diagnose_synthetic_harness.py
"""

from __future__ import annotations

import argparse
import logging
import tempfile
from collections.abc import Sequence
from datetime import UTC, datetime, timedelta
from pathlib import Path

import numpy

from phos.atlas.cmms import (
    SAP_PM_SCHEMA,
    WORK_ORDER_COVERAGE_IS_NOT_INNOCENCE,
    load_work_order_export,
    observations_from_work_orders,
)
from phos.atlas.work_orders import promote_work_orders, work_order_feature_of
from phos.breaking.commands import classify_command_issuer, read_command_path
from phos.reasoning.calibration import FittedPlattCalibrator
from phos.synth.catalogue_scenarios import scenarios_for
from phos.synth.command import Authorisation
from phos.synth.maintenance import (
    MAINTENANCE_IS_INDEPENDENT_OF_ATTACKS_CAVEAT,
    MaintenancePractice,
    plan_maintenance,
    write_sap_pm_export,
)
from phos.synth.plant import MODEL_NOT_REALITY_CAVEAT, RunSpec
from phos.synth.run import run_plant
from phos.synth.scenarios import ATTACKS_ARE_SPECIFIED_BY_INTENT_CAVEAT, Scenario
from phos.synth.traffic import TrafficPolicy, modbus_frames, write_pcap

logger = logging.getLogger(__name__)

BANNER = f"""
================================================================================
SYNTHETIC-DERIVED DIAGNOSTIC — NOT A MEASUREMENT, NOT A DETECTION CLAIM
================================================================================
{MODEL_NOT_REALITY_CAVEAT}

{ATTACKS_ARE_SPECIFIED_BY_INTENT_CAVEAT}

{MAINTENANCE_IS_INDEPENDENT_OF_ATTACKS_CAVEAT}

{WORK_ORDER_COVERAGE_IS_NOT_INNOCENCE}

Frozen public rows are untouched. Command-lead stays 0 of 16 (known station) and
1 of 4 (unknown master), unpooled. Nothing below is appended to eval_runs/log.jsonl.
================================================================================
"""

PLANT = "water-treatment"
ASSETS = ("intake", "dosing", "filtration", "clearwell", "distribution")
CERTAIN = FittedPlattCalibrator(coefficient=0.0, intercept=40.0)


def spec(seed: int, hours: int) -> RunSpec:
    """Return a 30-second-sampled run of ``hours`` hours."""
    return RunSpec(
        seed=seed,
        start=datetime(2026, 3, 1, tzinfo=UTC),
        duration=timedelta(hours=hours),
        sample_interval=timedelta(seconds=30),
    )


def capture(run_spec: RunSpec, scenario: Scenario | None, path: Path) -> object:
    """Simulate the works and write its control traffic to ``path``.

    Args:
        run_spec: The run.
        scenario: The adversary, or ``None`` for an ordinary day.
        path: Where to write the pcap.

    Returns:
        The completed run, so the caller can read its ground truth.
    """
    source = None
    if scenario is not None:
        low, high = 0.0, 6.0
        source = scenario.source(low=low, high=high)
    run = run_plant(PLANT, run_spec, commands=source)
    frames = modbus_frames(run.description, run.steps, TrafficPolicy(seed=run_spec.seed))
    written = write_pcap(frames, path)
    logger.info("wrote %d frame(s) to %s", written, path)
    return run


def question_one(baseline: Path, live: Path, run: object, scenario: Scenario) -> None:
    """Report what the command path sees when attacker command actions genuinely exist."""
    print("\n--- 1. Does the command path see an attacker's writes? ---\n")

    issued = [command for step in run.steps for command in step.issued]  # type: ignore[attr-defined]
    unauthorised = [c for c in issued if c.authorised is Authorisation.UNAUTHORISED]
    print(f"  scenario                    : {scenario.scenario_id}")
    print(f"  goal (plant's own terms)    : {scenario.goal.narrative}")
    print(f"  provenance                  : {scenario.provenance.kind.value}")
    print(f"  writes actually issued      : {len(issued)}")
    print(f"  of those, unauthorised      : {len(unauthorised)}  (declared policy, not the wire)")

    path = read_command_path(baseline, live)
    kind = classify_command_issuer(scenario.issuer, run.description, path.graph)  # type: ignore[attr-defined]
    print(f"  issuer                      : {scenario.issuer!r} -> {kind.value}")
    print(f"  graph findings              : {len(path.graph_findings)}")
    print(f"  command-behaviour features  : {len(path.live_features)}")

    for finding in path.graph_findings[:6]:
        print(f"    - {finding.feature} on {finding.entity_ids} = {finding.value}")

    print(
        "\n  READ THIS AS: machinery that had never been exercised now runs end to end on data\n"
        "  where an attacker's write really moved the process. It is NOT a lead rate, NOT a\n"
        "  recall figure, and it does not move the frozen 0 of 16 or 1 of 4."
    )


def question_two(run: object, run_spec: RunSpec, workdir: Path) -> object:
    """Report what the CMMS join does when a real calendar exists."""
    print("\n--- 2. Does the CMMS join do anything with a real calendar? ---\n")

    calendar = plan_maintenance(
        numpy.random.default_rng(run_spec.seed),
        run_spec,
        ASSETS,
        MaintenancePractice(routine_interval=timedelta(days=3), reactive_per_year=400.0),
    )
    export = workdir / "sap_pm_export.csv"
    write_sap_pm_export(calendar, export)

    records = load_work_order_export(export, SAP_PM_SCHEMA, declared_assets=ASSETS)
    observations = observations_from_work_orders(records)
    facts = promote_work_orders(observations, CERTAIN)

    print(f"  orders raised               : {len(calendar.orders)}")
    print(f"  of those, sanctioning       : {len(calendar.sanctioning())}")
    print(f"  read back by the adapter    : {len(records)}")
    print(f"  promoted into evidence      : {len(facts)}")
    if facts:
        stamped = work_order_feature_of(facts[0].evidence)
        print(f"  evidence reaches a template : {stamped!r} (the fact templates already spend)")
        print(f"  example summary             : {facts[0].evidence.summary}")

    print(
        "\n  READ THIS AS: the inlet ADR 0069 built has now been fed by a generated maintenance\n"
        "  system export, read by the real adapter, and promoted into the stamped evidence a\n"
        "  template reads. That is a wiring result. It is NOT evidence that a work order\n"
        "  improves any queue, ranking or explanation split — that claim stays unearned."
    )
    return calendar


def question_three(run: object, calendar: object, scenario: Scenario) -> None:
    """Report the covered-window case: an attacker acting inside a sanctioned window."""
    print("\n--- 3. The covered-window case ---\n")

    issued = [command for step in run.steps for command in step.issued]  # type: ignore[attr-defined]
    moments = [command.timestamp for command in issued]
    covered = calendar.covered_windows({scenario.asset_id: moments})  # type: ignore[attr-defined]

    print(f"  attacker writes             : {len(moments)}")
    print(f"  falling inside a sanctioned : {len(covered)}")
    print(f"  asset                       : {scenario.asset_id}")

    if covered:
        _, moment, order = covered[0]
        print(f"  example                     : write at {moment.isoformat()}")
        print(f"                                covered by {order.order_id} ({order.kind.value})")
        print(f"                                window {order.start} -> {order.end}")
        print(
            "\n  Atlas has, for this window: an unauthorised write in the ground truth, a graph\n"
            "  finding on the wire, AND a covering work order that CONTRADICTS\n"
            "  unauthorised_control_activity while SUPPORTING engineering_maintenance."
        )
    else:
        print(
            "\n  No attacker write landed inside a sanctioned window on this seed. That is the\n"
            "  honest outcome of two independent schedules: coverage is a coincidence, and on\n"
            "  some seeds the coincidence does not happen. Try another seed."
        )

    print(
        "\n  READ THIS AS: the case ADR 0014 and ADR 0069 both name is now constructible and\n"
        "  inspectable. ADR 0014's finding stands unchanged — a commissioning engineer and an\n"
        "  intruder leave the same evidence, and only the priors separate them. Nothing here\n"
        "  claims to have solved that, and a covering order remains not innocence."
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Run the diagnostic and print it."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--hours", type=int, default=24)
    parser.add_argument("--scenario", default="wt-clearwell-overfill-impatient")
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(name)s: %(message)s")
    print(BANNER)

    candidates = {item.scenario_id: item for item in scenarios_for(PLANT)}
    scenario = candidates.get(args.scenario)
    if scenario is None:
        print(f"no scenario {args.scenario!r}; this plant has: {', '.join(sorted(candidates))}")
        return 2

    run_spec = spec(args.seed, args.hours)
    with tempfile.TemporaryDirectory() as raw:
        workdir = Path(raw)
        baseline_path = workdir / "baseline.pcap"
        live_path = workdir / "live.pcap"

        capture(run_spec, None, baseline_path)
        live = capture(run_spec, scenario, live_path)

        question_one(baseline_path, live_path, live, scenario)
        calendar = question_two(live, run_spec, workdir)
        question_three(live, calendar, scenario)

    print("\n" + "=" * 80)
    print("SYNTHETIC-DERIVED. UNVALIDATED UNTIL REAL DATA ARRIVES. NOT A DETECTION CLAIM.")
    print("=" * 80)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
