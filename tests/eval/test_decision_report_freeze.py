"""The U5 report states its limitations before any number, and invents none.

The committed artefacts are regenerated by `scripts/run_u5_decision_study.py`. These pins
exist so a later edit that headlines a usefulness score, drops the non-operator banner, or
treats the mechanical delta as a field result turns red.
"""

from __future__ import annotations

import json
from pathlib import Path

from scripts.run_u5_decision_study import run_instrument_check

from phos.eval.decision_report import _time_line, render_study_json, render_study_markdown
from phos.eval.decision_study import (
    CRUDE_RUN_LABEL,
    NOT_A_FIELD_STUDY,
    NOT_OPERATIONAL_USEFULNESS,
    SENTIEL_SETTLING_LIMITATION,
    SYNTHETIC_DERIVED_BANNER,
    Arm,
    ArmAggregate,
)

REPO = Path(__file__).resolve().parents[2]
REPORT = REPO / "eval_runs" / "usefulness" / "u5-decision-study.md"
REPORT_JSON = REPO / "eval_runs" / "usefulness" / "u5-decision-study.json"
LOG = REPO / "eval_runs" / "log.jsonl"


def test_limitations_precede_any_table() -> None:
    result = run_instrument_check(git_commit="test")
    text = render_study_markdown(result)
    assert text.index(CRUDE_RUN_LABEL) < text.index("## Primary comparison")
    assert text.index(NOT_A_FIELD_STUDY) < text.index("| Arm |")
    assert text.index(NOT_OPERATIONAL_USEFULNESS) < text.index("| Arm |")
    assert text.index(SENTIEL_SETTLING_LIMITATION) < text.index("## Primary comparison")
    assert SYNTHETIC_DERIVED_BANNER in text
    assert "Not collected" in text
    assert "**0**" in text.split("## Time to correct conclusion", 1)[1]


def test_json_has_no_usefulness_score_and_claims_nothing() -> None:
    result = run_instrument_check(git_commit="test")
    payload = render_study_json(result)
    assert "usefulness_score" not in payload
    assert "accuracy" not in payload
    assert payload["label"] == CRUDE_RUN_LABEL
    assert payload["operational_usefulness_claim"] is False
    assert payload["plant_literate"] is False
    assert payload["n_human"] == 0
    assert payload["logged_to_eval_runs_log"] is False
    assert payload["synthetic_derived"] is True
    assert payload["sentiel_settling_is_weak"] is True
    assert payload["n_atlas_cases"] == 6
    assert payload["n_sentiel_cases"] == 1
    assert payload["n_scores"] == 21


def test_markdown_counts_match_the_json() -> None:
    result = run_instrument_check(git_commit="test")
    text = render_study_markdown(result)
    payload = render_study_json(result)
    for row in payload["primary"]:
        assert f"`{row['arm']}` | {row['n']} | {row['n_correct']}" in text
        assert row["n"] == 6
    for row in payload["sentiel"]:
        assert row["n"] == 1


def test_committed_report_keeps_the_banner_first() -> None:
    assert REPORT.is_file(), "run scripts/run_u5_decision_study.py before claiming U5 complete"
    text = REPORT.read_text(encoding="utf-8")
    assert text.index(CRUDE_RUN_LABEL) < text.index("## Primary comparison")
    assert NOT_A_FIELD_STUDY in text
    assert SENTIEL_SETTLING_LIMITATION in text
    payload = json.loads(REPORT_JSON.read_text(encoding="utf-8"))
    assert payload["n_human"] == 0
    assert "usefulness_score" not in payload


def test_nothing_is_appended_to_the_eval_log_by_this_module() -> None:
    """U5 must never write a public row. The test does not run the writer against the log."""
    source = (REPO / "scripts" / "run_u5_decision_study.py").read_text(encoding="utf-8")
    assert "Never appends" in source
    assert LOG.is_file()


def test_time_line_reports_means_only_from_counts() -> None:
    """A timed arm's mean is sum_elapsed_ms / n_with_time. Untimed arms stay silent."""
    timed = ArmAggregate(
        arm=Arm.RAW_TELEMETRY,
        n=2,
        n_correct=1,
        n_incorrect=1,
        n_false_escalation=0,
        n_missed_uncertainty=0,
        n_evidence_requested=0,
        n_overconfident_wrong=0,
        n_with_time=2,
        sum_elapsed_ms=3000,
    )
    silent = ArmAggregate(
        arm=Arm.THRESHOLD_ALERT,
        n=2,
        n_correct=0,
        n_incorrect=2,
        n_false_escalation=0,
        n_missed_uncertainty=0,
        n_evidence_requested=0,
        n_overconfident_wrong=0,
        n_with_time=0,
        sum_elapsed_ms=0,
    )
    text = _time_line((timed, silent))
    assert "mean 1500.0 ms over 2 timed trials" in text
    assert "no times" in text
