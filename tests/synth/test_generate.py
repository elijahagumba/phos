"""The whole path, end to end: config in, a corpus Atlas can read out.

Every other test in this package checks one seam. This one checks that the seams join: a committed
config produces a directory of files, and those files go into Atlas through the three doors it
already has — `phos.eval.LabelledCsvAdapter` for telemetry, `phos.atlas.topology.load_topology`
for the topology, `phos.atlas.packet.dissect_capture` for the capture — with no argument, option
or branch anywhere that exists because the data is synthetic.

It also checks the two claims the manifest makes about itself: that its digests describe the files
actually written, and that regenerating from the same config reproduces them exactly.
"""

from datetime import UTC, datetime
from pathlib import Path

import pytest
from scripts.generate_synth import main

import phos.synth.generate
from phos.atlas.packet import (
    CaptureStats,
    DissectorRegistry,
    MalformedFrame,
    ModbusDissector,
    ModbusMessage,
    UnparsedMessage,
    dissect_capture,
)
from phos.atlas.topology import load_topology
from phos.atlas.vectorise import SignalSpace, vectorise
from phos.eval import LabelledCsvAdapter
from phos.synth.catalogue import DatasetConfig
from phos.synth.generate import (
    CAPTURE_FILE,
    MANIFEST_FILE,
    TELEMETRY_FILE,
    TOPOLOGY_FILE,
    GenerationError,
    generate_dataset,
)
from phos.synth.manifest import SynthManifest, digest_of
from phos.synth.plant import SYNTHETIC_DERIVED, RunSpec
from phos.synth.realism import RealismProfile
from phos.synth.run import PlantRun, run_plant
from phos.synth.sidecar import REALISM_FILE
from phos.synth.telemetry import LABEL_COLUMN, TIMESTAMP_COLUMN

START = datetime(2026, 11, 1, tzinfo=UTC)


def config_for(plant_id: str, name: str, hours: float, interval: float) -> DatasetConfig:
    """Return a short config, so the integration tests stay quick without being toys."""
    return DatasetConfig(
        name=name,
        plant_id=plant_id,
        seed=4242,
        traffic_seed=77,
        start=START,
        duration_hours=hours,
        sample_interval_seconds=interval,
        role="train",
        note="generated by a test",
    )


WATER = config_for("water-treatment", "test-water", 3.0, 30.0)
BATCH = config_for("batch-reactor", "test-batch", 8.0, 60.0)


def manifest_of(directory: Path) -> SynthManifest:
    """Read the manifest a generation run wrote."""
    return SynthManifest.model_validate_json(
        (directory / MANIFEST_FILE).read_text(encoding="utf-8")
    )


class TestGeneratingOneCorpus:
    def test_it_writes_telemetry_topology_capture_and_a_manifest(self, tmp_path: Path) -> None:
        directory, _ = generate_dataset(WATER, tmp_path)
        assert sorted(path.name for path in directory.iterdir()) == sorted(
            [TELEMETRY_FILE, TOPOLOGY_FILE, CAPTURE_FILE, MANIFEST_FILE]
        )

    def test_a_plant_with_no_control_network_gets_no_capture_and_says_so(
        self, tmp_path: Path
    ) -> None:
        directory, _ = generate_dataset(BATCH, tmp_path)
        assert not (directory / CAPTURE_FILE).exists()
        assert {file.kind for file in manifest_of(directory).files} == {
            "telemetry-csv",
            "topology-toml",
        }

    def test_the_capture_can_be_left_out_on_request(self, tmp_path: Path) -> None:
        directory, _ = generate_dataset(WATER, tmp_path, with_capture=False)
        assert not (directory / CAPTURE_FILE).exists()
        assert (directory / TELEMETRY_FILE).exists()

    def test_the_manifest_digests_describe_the_files_that_were_written(
        self, tmp_path: Path
    ) -> None:
        directory, returned = generate_dataset(WATER, tmp_path)
        assert returned == manifest_of(directory)
        for file in manifest_of(directory).files:
            sha256, size = digest_of(directory / file.filename)
            assert (file.sha256, file.size_bytes) == (sha256, size)

    def test_regenerating_from_one_config_reproduces_every_byte(self, tmp_path: Path) -> None:
        first, _ = generate_dataset(WATER, tmp_path / "first")
        second, _ = generate_dataset(WATER, tmp_path / "second")
        for name in (TELEMETRY_FILE, TOPOLOGY_FILE, CAPTURE_FILE):
            assert (first / name).read_bytes() == (second / name).read_bytes()

    def test_a_config_that_holds_no_samples_is_refused_rather_than_written_empty(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        def empty(
            plant_id: str,
            spec: RunSpec,
            injection: object = None,
            commands: object = None,
            realism: object = None,
        ) -> PlantRun:
            produced = run_plant(plant_id, spec)
            return PlantRun(
                plant_id=produced.plant_id,
                description=produced.description,
                spec=produced.spec,
                steps=(),
                events=produced.events,
            )

        monkeypatch.setattr(phos.synth.generate, "run_plant", empty)
        with pytest.raises(GenerationError, match="holds no samples"):
            generate_dataset(WATER, tmp_path)


class TestTheCorpusGoesIntoAtlasThroughTheDoorsItAlreadyHas:
    def test_the_telemetry_loads_with_the_unmodified_csv_adapter(self, tmp_path: Path) -> None:
        directory, _ = generate_dataset(WATER, tmp_path)
        dataset = LabelledCsvAdapter(
            path=directory / TELEMETRY_FILE,
            timestamp_column=TIMESTAMP_COLUMN,
            label_column=LABEL_COLUMN,
            name=WATER.name,
        ).load()
        assert dataset.attack_intervals == []
        assert dataset.normal_duration() == dataset.duration()
        assert len(dataset.observations) == 360 * 15

    def test_the_loaded_corpus_reshapes_for_a_joint_model_with_nothing_dropped(
        self, tmp_path: Path
    ) -> None:
        directory, _ = generate_dataset(WATER, tmp_path)
        dataset = LabelledCsvAdapter(
            path=directory / TELEMETRY_FILE,
            timestamp_column=TIMESTAMP_COLUMN,
            label_column=LABEL_COLUMN,
        ).load()
        space = SignalSpace.from_observations(dataset.observations)
        series = vectorise(dataset.observations, space)
        assert space.size == 15
        assert series.n_rows == 360
        assert series.dropped_timestamps == 0

    def test_the_topology_loads_against_the_columns_the_csv_actually_has(
        self, tmp_path: Path
    ) -> None:
        directory, _ = generate_dataset(WATER, tmp_path)
        header = (directory / TELEMETRY_FILE).read_text(encoding="utf-8").splitlines()[0]
        columns = set(header.split(",")[2:])
        topology = load_topology(directory / TOPOLOGY_FILE, columns, corpus=WATER.plant_id)
        assert sum(len(subsystem.signals) for subsystem in topology) == len(columns)

    def test_the_capture_dissects_without_one_malformed_frame(self, tmp_path: Path) -> None:
        directory, _ = generate_dataset(WATER, tmp_path)
        stats = CaptureStats()
        results = list(
            dissect_capture(directory / CAPTURE_FILE, DissectorRegistry([ModbusDissector()]), stats)
        )
        assert results
        assert all(isinstance(result, ModbusMessage) for result in results)
        assert not [result for result in results if isinstance(result, MalformedFrame)]
        assert not [result for result in results if isinstance(result, UnparsedMessage)]
        assert stats.accounts_for_every_frame()

    def test_a_batch_corpus_loads_the_same_way_without_a_capture(self, tmp_path: Path) -> None:
        directory, _ = generate_dataset(BATCH, tmp_path)
        dataset = LabelledCsvAdapter(
            path=directory / TELEMETRY_FILE,
            timestamp_column=TIMESTAMP_COLUMN,
            label_column=LABEL_COLUMN,
        ).load()
        columns = {observation.feature for observation in dataset.observations}
        load_topology(directory / TOPOLOGY_FILE, columns, corpus=BATCH.plant_id)
        assert len(columns) == 13


class TestTheCommandLine:
    def test_listing_the_standard_datasets_succeeds(self) -> None:
        assert main(["--list"]) == 0

    def test_no_arguments_lists_rather_than_generating_gigabytes(self) -> None:
        assert main([]) == 0

    def test_a_named_dataset_is_generated_into_the_requested_directory(
        self, tmp_path: Path
    ) -> None:
        assert main(["synth-batch-reactor-holdout", "--output", str(tmp_path)]) == 0
        assert (tmp_path / "synth-batch-reactor-holdout" / TELEMETRY_FILE).exists()

    def test_an_unknown_dataset_is_refused_with_the_known_ones_named(self, tmp_path: Path) -> None:
        assert main(["synth-refinery", "--output", str(tmp_path)]) == 2
        assert not list(tmp_path.iterdir())

    def test_generating_everything_is_available_behind_one_flag(self, tmp_path: Path) -> None:
        assert main(["--all", "--output", str(tmp_path), "--no-capture"]) == 0
        assert len(list(tmp_path.iterdir())) == 6


class TestRealismSidecarAndDropouts:
    def test_a_quiet_run_writes_no_sidecar_and_the_same_files_as_before(
        self, tmp_path: Path
    ) -> None:
        directory, manifest = generate_dataset(WATER, tmp_path)
        assert not (directory / REALISM_FILE).exists()
        assert REALISM_FILE not in {item.filename for item in manifest.files}
        assert sorted(path.name for path in directory.iterdir()) == sorted(
            [TELEMETRY_FILE, TOPOLOGY_FILE, CAPTURE_FILE, MANIFEST_FILE]
        )

    def test_a_non_quiet_run_writes_a_labelled_sidecar_listed_in_the_manifest(
        self, tmp_path: Path
    ) -> None:
        directory, manifest = generate_dataset(
            WATER, tmp_path, realism=RealismProfile(sensor_faults=2)
        )
        sidecar = directory / REALISM_FILE
        assert sidecar.exists()
        text = sidecar.read_text(encoding="utf-8")
        assert SYNTHETIC_DERIVED in text
        listed = next(item for item in manifest.files if item.filename == REALISM_FILE)
        sha256, size = digest_of(sidecar)
        assert (listed.sha256, listed.size_bytes) == (sha256, size)

    def test_planned_dropouts_change_the_capture(self, tmp_path: Path) -> None:
        quiet, _ = generate_dataset(WATER, tmp_path / "quiet")
        noisy, _ = generate_dataset(
            WATER, tmp_path / "noisy", realism=RealismProfile(comms_dropouts=2)
        )
        assert (quiet / CAPTURE_FILE).read_bytes() != (noisy / CAPTURE_FILE).read_bytes()

    def test_the_sidecar_is_not_an_atlas_input(self) -> None:
        """Atlas never reads realism.json — checked as a property of the atlas tree."""
        root = Path(__file__).resolve().parents[2] / "src" / "phos" / "atlas"
        offences = [
            str(path.relative_to(root.parent.parent))
            for path in root.rglob("*.py")
            if "realism.json" in path.read_text(encoding="utf-8")
        ]
        assert offences == []
